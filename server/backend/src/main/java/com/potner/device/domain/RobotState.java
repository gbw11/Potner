package com.potner.device.domain;

/**
 * 로봇의 현재 행동 상태다. 젯슨이 정하고 서버에 알린다.
 *
 * <p>값은 하드웨어팀이 정의한 것을 그대로 쓴다. 서버가 이름을 바꾸면 페이로드를 옮겨 담는
 * 변환 계층이 하나 더 생기고, 그 계층이 새 상태를 모르면 조용히 버린다.
 *
 * <p>{@link #SERVICING} 이 급수와 송풍을 함께 가리킨다. 서버는 둘을 구별할 수 없다. 표정은
 * 어느 쪽이든 같아서 문제가 없지만, 급수 완료를 이 상태로 판정하려 하면 송풍을 급수로 볼 수
 * 있다. 급수 작업은 자기가 보낸 명령과 짝지어 판정해야 한다.
 */
public enum RobotState {

    /** 대기 중이다. 센서를 보고 있다. 어디에서 대기하는지는 이 값으로 알 수 없다. */
    IDLE,

    /** 목적지로 이동 중이다. */
    NAVIGATING,

    /** 마커를 보며 정밀 접근 중이다. */
    DOCKING,

    /** 급수 또는 송풍을 받는 중이다. */
    SERVICING,

    /** 사용자를 반기는 중이다. */
    GREETING
}
