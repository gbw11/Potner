-- 사용자가 알림 목록에서 치운 시각이다.
--
-- 앱에서 알림을 왼쪽으로 밀면 감췄지만 그건 앱 메모리에만 남아서, 다시 들어오면 서버에서 그대로
-- 내려와 되살아났다. 치웠다는 것은 사용자 의도라 서버에 남아야 한다 — 기기에만 두면 앱을 다시
-- 깔거나 다른 기기에서 보면 또 나타난다.
--
-- 행을 지우지 않는 이유가 셋이다. 지우면 되돌릴 수 없는 것에 더해:
--
--   1. 행복도 점수가 소급해서 바뀐다. StatusReportService 는 점수를 저장하지 않고 조회할 때마다
--      그 날짜의 알림을 세어 100 점에서 깎는다. 알림이 사라지면 지난 날의 점수가 올라간다.
--   2. 자동화가 다시 돈다. 자동 급수·자동 말리기는 "해소되지 않은 알림" 을 보고 트리거되고
--      (AutoDryingScheduler.dryOnce), 열린 알림이 있으면 중복 실행을 막는다. 열린 알림을 지우면
--      서버는 이상이 없었던 것으로 보고 같은 알림을 새로 만들며 체인을 다시 시작한다.
--   3. 그날 일기가 달라진다. PlantDaySummaryReader 가 알림을 LLM 근거로 넘긴다.
--
-- resolved_at 을 재활용하지 않는 이유도 2번이다. 그쪽은 "이상이 해소됨" 이라 자동화가 읽는 값이고,
-- 여기는 "사용자가 목록에서 치움" 이라 목록 조회만 본다.
ALTER TABLE `alert`
    ADD COLUMN `dismissed_at` DATETIME NULL COMMENT '사용자가 목록에서 치운 시각. 목록 조회만 참조한다'
    AFTER `read_at`;

-- 목록 조회는 user_id 로 좁힌 뒤 이 컬럼을 보므로 단독 인덱스를 두지 않는다. 한 사용자의 알림
-- 수가 인덱스가 필요할 만큼 많아지면 (user_id, dismissed_at) 복합으로 그때 넣는다.
