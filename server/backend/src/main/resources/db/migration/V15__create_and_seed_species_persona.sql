-- 종마다 다른 말투로 일기를 쓰기 위한 페르소나다. 꽃말을 성격으로 옮긴 기획 자료(v2.1)에서 왔다.
--
-- 기획 자료의 완성된 system_prompt 를 통째로 담지 않는다. 그 프롬프트는 일곱 필드짜리 출력
-- (mood·facts_used·persona_signature 등)을 요구하는데 우리가 저장하는 것은 제목과 본문뿐이고,
-- 채울 수 없는 런타임 입력(COMPLETED_ACTIONS_JSON, USER_MEMORY_JSON)을 전제한다. 조립에 필요한
-- 조각만 컬럼으로 두고 일기용 프롬프트는 코드가 만든다.
--
-- 컬럼이 많은 이유는 기획 자료의 핵심이 '종마다 확실히 다르게 쓰이는 것'이기 때문이다.
-- 말투 한 줄만 주면 모델이 전부 비슷하게 쓴다. 관찰 초점, 문장 구조, 대표 어휘, 금지 문체,
-- 결말 규칙까지 넘겨야 서정형과 보고서형이 갈린다.
--
-- 관찰 초점과 전개에서 사용자 관련 항목은 뺐다. 원본은 "사용자와 함께한 순간", "사용자 등장
-- 전후의 공간 변화", "사용자의 컨디션" 을 보라고 하는데 서버는 재실도 컨디션도 모른다.
-- 근거 없는 것을 보라고 하면 모델이 지어낸다. 로봇 행동을 뺀 것과 같은 이유다.
