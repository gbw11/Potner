    -- 사라지므로 "무엇이 아닌가"를 함께 준다.
    `contrast_anchor` VARCHAR(300) NOT NULL COMMENT '다른 종과 구별되는 기준',

    -- 문체 예시다. 기획 자료의 예시를 그대로 쓰지 않았다.
    -- v1, v2, v2.1 모두 예시가 "밝은 자리로 이동했다", "물을 받고" 처럼 로봇 행동을 말하는데,
    -- 같은 자료의 안전 규칙은 하지 않은 행동을 썼다고 하지 말라고 한다. 서버는 아직 이동도
    -- 급수도 하지 않으므로 원본을 예시로 주면 모델이 문체를 따라 하며 없는 행동을 지어낸다.
    -- 말투와 구조는 유지하고 행동 문장만 걷어낸 형태로 다시 썼다.
    `diary_example`   VARCHAR(500) NOT NULL COMMENT '행동 언급을 뺀 문체 예시',

    CONSTRAINT `pk_species_persona` PRIMARY KEY (`species_id`),
    CONSTRAINT `fk_species_persona_species`
        FOREIGN KEY (`species_id`) REFERENCES `plant_species` (`species_id`) ON DELETE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
