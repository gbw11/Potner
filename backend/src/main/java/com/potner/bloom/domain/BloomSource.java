package com.potner.bloom.domain;

/**
 * 개화 기록을 누가 남겼는지다.
 *
 * <p>지금 만들어지는 기록은 전부 {@link #USER} 다. {@link #DEVICE} 를 미리 두는 이유는 장치가
 * 개화를 판정하게 됐을 때 사용자가 이미 남긴 기록과 구분할 수단이 필요하기 때문이다. 구분이
 * 없으면 같은 개화가 두 건으로 남았을 때 어느 쪽을 지워야 하는지 알 수 없다.
 */
public enum BloomSource {

    /** 사용자가 앱에서 직접 남겼다. */
    USER,

    /** 장치가 판정해 남겼다. 아직 이 값을 만드는 경로는 없다. */
    DEVICE
}
