package com.potner.command.domain;

/**
 * 자동 명령이 속한 체인이다. 사용자 명령에는 없다({@code null}).
 *
 * <p>세 체인이 모두 "스테이션으로 이동 → 작업 → 대기 장소 복귀" 라는 같은 모양이라, 이 값이
 * 없으면 도착 회신만 보고는 어느 체인인지 알 수 없다. 촬영하러 간 로봇에 급수 명령이 나가는
 * 사고가 그래서 생긴다.
 *
 * <p>펌프·팬·카메라가 모두 스테이션에 고정되어 있어 세 작업 다 이동이 앞선다. 장치가 화분
 * 쪽으로 옮겨가면 이동 단계만 빠지고 이 구분은 그대로 쓸 수 있다.
 */
public enum CommandPurpose {

    /** 토양 수분 부족 → 급수. */
    WATERING,

    /** 하루 한 장 성장 사진. */
    CAPTURE,

    /** 토양 과습 → 송풍으로 말리기. */
    DRYING,

    /**
     * 하루 광량을 채우기 위한 자리 옮김. 뒤에 이어지는 단계가 없는 단발 이동이라 체인은 아니지만,
     * 명령 이력에서 "이 로봇이 왜 움직였나" 를 답할 수 있어야 해서 함께 남긴다.
     */
    RELOCATION
}
