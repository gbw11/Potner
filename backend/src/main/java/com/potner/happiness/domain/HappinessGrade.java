package com.potner.happiness.domain;

/**
 * 홈 화면에 보여줄 현재 상태 등급이다.
 *
 * <p>기준을 벗어난 센서 지표 수로 정한다. 점수({@code status-report})와 다르다. 점수는 하루가
 * 지난 뒤 그날을 돌아보는 값이고, 등급은 지금을 말한다. 홈 화면이 "실시간" 이라고 적혀 있는
 * 이유이며, 두 값을 하나로 합치면 어느 쪽도 정확하지 않게 된다.
 *
 * <p>로봇 디스플레이 표정({@code PlantExpression})과도 다르다. 표정은 지금 하는 행동까지
 * 반영해 매우행복이 있지만, 등급은 환경만 본다. 물을 마시는 중이라고 온도가 나아지지는 않는다.
 */
public enum HappinessGrade {

    /** 기준을 벗어난 지표가 없다. */
    GOOD,

    /** 하나가 기준을 벗어났다. */
    FAIR,

    /** 둘 이상이 기준을 벗어났다. */
    POOR,

    /**
     * 판정할 근거가 없다.
     *
     * <p>신선한 측정값이 하나도 없거나 생육 기준이 없는 경우다. {@link #GOOD} 으로 처리하면
     * 로봇이 꺼져 있는 동안 "아주 좋아요" 를 보여주게 된다.
     */
    UNKNOWN
}
