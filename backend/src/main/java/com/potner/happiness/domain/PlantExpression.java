package com.potner.happiness.domain;

/**
 * 로봇 디스플레이에 그릴 표정이다.
 *
 * <p>점수가 아니라 네 단계다. 앱에는 보이지 않고 로봇 화면에만 나가므로 숫자를 줄 이유가 없다.
 *
 * <p>온·습도가 바탕(baseline)을 정하고, 행동이 일어나면 그 위를 덮는다. 행동 쪽이 이긴다.
 * 환경이 나빠도 물을 마시는 순간은 기뻐야 사용자가 자기 행동의 결과를 읽을 수 있다.
 *
 * <p>{@link #VERY_HAPPY} 는 로봇 상태를 받기 시작한 뒤에 나온다. 지금은 만들어지지 않지만
 * 값은 미리 둔다. 하드웨어팀이 네 표정을 한 번에 그릴 수 있어야 나중에 계약이 바뀌지 않는다.
 */
public enum PlantExpression {

    /** 급수·송풍을 받는 중이거나 사용자를 반기는 중이다. */
    VERY_HAPPY,

    /** 충분한 광량을 받고 있거나, 오늘 꽃이 폈거나, 물을 마신 직후다. */
    HAPPY,

    /** 특별한 일이 없다. 온·습도가 기준 안이다. */
    NEUTRAL,

    /** 온도나 습도가 기준을 벗어났다. */
    SAD
}
